// Altitude do sol (graus) para uma latitude/longitude e um instante.
// Algoritmo simplificado da NOAA; erro de menos de 1°, suficiente para a interface.

const rad = Math.PI / 180;

export const FLORIPA = { lat: -27.5954, lon: -48.548 };

export function sunAltitude(date: Date, lat = FLORIPA.lat, lon = FLORIPA.lon) {
  const jd = date.getTime() / 86400000 + 2440587.5;
  const n = jd - 2451545.0;
  const L = (280.46 + 0.9856474 * n) % 360;
  const g = ((357.528 + 0.9856003 * n) % 360) * rad;
  const lambda = (L + 1.915 * Math.sin(g) + 0.02 * Math.sin(2 * g)) * rad;
  const eps = (23.439 - 0.0000004 * n) * rad;
  const ra = Math.atan2(Math.cos(eps) * Math.sin(lambda), Math.cos(lambda));
  const dec = Math.asin(Math.sin(eps) * Math.sin(lambda));
  const gmst = (18.697374558 + 24.06570982441908 * n) % 24;
  const lst = (gmst * 15 + lon) * rad;
  const ha = lst - ra;
  const alt = Math.asin(Math.sin(lat * rad) * Math.sin(dec) + Math.cos(lat * rad) * Math.cos(dec) * Math.cos(ha));
  return alt / rad;
}

export function floripaTime(date: Date) {
  return new Intl.DateTimeFormat("pt-BR", {
    timeZone: "America/Sao_Paulo",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

/** Hora dourada: sol entre -4° e 8°. */
export const isGoldenHour = (alt: number) => alt > -4 && alt < 8;
